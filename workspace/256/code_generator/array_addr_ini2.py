import re

def generate_and_save_to_file(input_data, base_address, array_name, filename="inv_addr.txt", mode='w'):
    instructions = [] # 用來儲存 (位址, 數值) 的配對
    current_addr = base_address

    # 1. 逐行解析資料
    lines = input_data.strip().split('\n')
    for line in lines:
        line = line.split('//')[0].strip() # 去除註解
        if not line:
            continue

        # 處理 .word：記錄數值並推進位址
        if line.startswith('.word'):
            clean_line = line.replace('.word', '').strip()
            values = [v.strip() for v in clean_line.split(',') if v.strip()]
            for v in values:
                instructions.append((current_addr, int(v)))
                current_addr += 4 

        # 處理 .space：將這段空間填滿 0
        elif line.startswith('.space'):
            match = re.search(r'\((.*?)\)', line)
            if match:
                expr = match.group(1)
                # 計算總共要跳過幾個 byte
                if '*' in expr:
                    parts = expr.split('*')
                    skip_bytes = int(parts[0].strip()) * int(parts[1].strip())
                else:
                    skip_bytes = int(expr.strip())
                
                # 計算這段 space 相當於幾個 int32 (除以 4)
                num_zeros = skip_bytes // 4
                
                # 把 0 逐一填入這段記憶體
                for _ in range(num_zeros):
                    instructions.append((current_addr, 0))
                    current_addr += 4

    # 2. 生成格式化字串 (一行兩個 mov)
    output_lines = []
    output_lines.append(f"// for {array_name}")
    
    for i in range(0, len(instructions), 2):
        addr1, val1 = instructions[i]
        cmd1 = f"mov L0x{addr1:x} ({val1:10d})@int32;"
        
        if i + 1 < len(instructions):
            addr2, val2 = instructions[i+1]
            cmd2 = f"mov L0x{addr2:x} ({val2:10d})@int32;"
            output_lines.append(f"{cmd1}{cmd2}")
        else:
            output_lines.append(f"{cmd1}")
    
    output_lines.append("\n")

    # 3. 寫入檔案
    with open(filename, mode, encoding="utf-8") as f:
        f.write("\n".join(output_lines))
    
    print(f"成功！已解析 {len(instructions)} 個數值 (包含補 0)，並寫入至 {filename}")

