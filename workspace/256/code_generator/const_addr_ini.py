import re

def convert_asm_to_mov(raw_text, target_address_hex):
    """
    將匯編風格的數據轉換為指定地址的 mov 指令
    :param raw_text: 原始的 .word 數據字串
    :param target_address_hex: 起始地址字串 (例如 "0x555555570450")
    :return: 格式化後的指令字串
    """
    # 轉為整數地址
    current_addr = int(target_address_hex, 16)
    
    # 提取所有數字：只找 .word 後面的內容
    numbers = []
    lines = raw_text.strip().split('\n')
    for line in lines:
        if '.word' in line:
            # 取得該行 .word 之後的所有數字
            data_part = line.split('.word')[-1]
            line_nums = re.findall(r'\d+', data_part)
            numbers.extend([int(n) for n in line_nums])
    
    # 產生指令
    results = []
    temp_row = []
    
    for val in numbers:
        addr_str = hex(current_addr).replace('0x', 'L0x')
        # 格式化指令，數字部分給予 10 格空間對齊
        cmd = f"mov {addr_str} ({val:10d})@int32"
        temp_row.append(cmd)
        
        # 每兩個一組進行換行處理
        if len(temp_row) == 2:
            results.append(";".join(temp_row) + ";")
            temp_row = []
            
        current_addr += 4 # int32 佔 4 bytes
        
    # 處理最後剩餘的一個（如果有話）
    if temp_row:
        results.append(";".join(temp_row) + ";")
        
    return "\n".join(results)

